import 'dart:convert';
import 'dart:io';

import 'package:neon_check/src/context.dart';
import 'package:neon_check/src/process.dart';

/// A flow that failed and the log that says why.
typedef FlowFailure = ({String flow, String log});

/// What a run of flows came to: the failing flows (empty = all passed) and the
/// whole output.
typedef FlowsResult = ({List<FlowFailure> failed, String output});

/// The generated target of a combined run, inside the integration folder
/// (the web compiler serves the target's folder as the app root, so the flows
/// must be importable from it). Kept out of git through `.git/info/exclude`.
const combinedTargetName = '_neon_check_flows.dart';

/// Runs [flows] on the app's driver.
///
/// With `integration.combine` and more than one flow the flows run from ONE
/// generated target (one build); a failure there is confirmed by running the
/// flows it names on their own, so a flow is reported only when it fails
/// alone too, with its own log. When the failure names no flow (a compile
/// error, a crash), every flow runs on its own.
Future<FlowsResult> runFlows(CheckContext context, List<String> flows) async {
  if (flows.isEmpty) return (failed: <FlowFailure>[], output: '');
  if (!context.config.integrationCombine || flows.length == 1) return _runEach(context, flows);
  final target = writeCombinedTarget(context, flows);
  try {
    final combined = await _runScript(context, [target]);
    if (combined.exitCode == 0) return (failed: <FlowFailure>[], output: combined.output);
    final suspects = attributeFailures(context, flows, combined.output);
    final alone = await _runEach(context, suspects.isEmpty ? flows : suspects);
    return (failed: alone.failed, output: '${combined.output}\n${alone.output}');
  } finally {
    final file = File(context.absolute(target));
    if (file.existsSync()) file.deleteSync();
  }
}

Future<FlowsResult> _runEach(CheckContext context, List<String> flows) async {
  final result = await _runScript(context, flows);
  final failed = [
    for (final match in RegExp(r'^integration: FAILED (\S+)(?: (\S+))?$', multiLine: true).allMatches(result.output))
      (flow: match.group(1) ?? context.config.integrationDir, log: match.group(2) ?? ''),
  ];
  if (result.exitCode != 0 && failed.isEmpty) failed.add((flow: context.config.integrationDir, log: ''));
  return (failed: failed, output: result.output);
}

Future<({int exitCode, String output})> _runScript(CheckContext context, List<String> files) async {
  final config = context.config;
  final defines = config.integrationDefinesFile;
  final result = await runProcess(context.root, '${context.toolRoot}/integration/run.sh', [
    '--driver',
    config.integrationDriver,
    if (config.integrationDevice.isNotEmpty) ...['--device', config.integrationDevice],
    if (defines.isNotEmpty && File(context.absolute(defines)).existsSync()) ...['--defines', defines],
    '--',
    ...files,
  ]);
  return (exitCode: result.exitCode, output: '${result.stdout}\n${result.stderr}');
}

/// Writes the combined target for [flows] and returns its root-relative path.
///
/// The integration binding is initialised before the groups: the binding
/// reports the results in a `tearDownAll` it registers when it is created,
/// and created inside the first flow's group it would report after that
/// group, ending the run. Each flow is a group named by its file, followed by
/// the app's `resetBetweenFlows()` (`integration.reset`) when there is one.
String writeCombinedTarget(CheckContext context, List<String> flows) {
  final config = context.config;
  final dir = config.integrationDir;
  final reset = config.integrationReset;
  String relative(String path) => path.startsWith('$dir/') ? path.substring(dir.length + 1) : path;
  final source = StringBuffer()
    ..writeln('// GENERATED by neon-check for one combined integration run; deleted after it.')
    ..writeln("import 'package:flutter_test/flutter_test.dart';")
    ..writeln("import 'package:integration_test/integration_test.dart';");
  if (reset.isNotEmpty) source.writeln("import '${relative(reset)}' as reset;");
  for (var i = 0; i < flows.length; i++) {
    source.writeln("import '${relative(flows[i])}' as flow$i;");
  }
  source
    ..writeln()
    ..writeln('void main() {')
    ..writeln('  IntegrationTestWidgetsFlutterBinding.ensureInitialized();');
  for (var i = 0; i < flows.length; i++) {
    source.writeln("  group('${flows[i]}', () {");
    if (reset.isNotEmpty) source.writeln('    tearDown(reset.resetBetweenFlows);');
    source
      ..writeln('    flow$i.main();')
      ..writeln('  });');
  }
  source.writeln('}');
  final target = '$dir/$combinedTargetName';
  File(context.absolute(target)).writeAsStringSync(source.toString());
  _excludeFromGit(context.root, '/$target');
  return target;
}

/// Adds [pattern] to the checkout's `.git/info/exclude` (local, never
/// committed), so the generated target is invisible to git and to the scope.
void _excludeFromGit(String root, String pattern) {
  final path = Process.runSync('git', ['rev-parse', '--git-path', 'info/exclude'], workingDirectory: root);
  if (path.exitCode != 0) return;
  final relative = (path.stdout as String).trim();
  final file = File(relative.startsWith('/') ? relative : '$root/$relative');
  final lines = file.existsSync() ? file.readAsLinesSync() : <String>[];
  if (lines.contains(pattern)) return;
  file
    ..createSync(recursive: true)
    ..writeAsStringSync('${lines.isEmpty ? '' : '${lines.join('\n')}\n'}$pattern\n');
}

/// The flows of [flows] whose test a combined run's output reports as
/// failed (`Failure in method: <test description>`). Empty when a failure
/// names no known test.
List<String> attributeFailures(CheckContext context, List<String> flows, String output) {
  final failing = {
    for (final match in RegExp(r'^Failure in method: (.+)$', multiLine: true).allMatches(output))
      (match.group(1) ?? '').trim(),
  };
  if (failing.isEmpty) return const [];
  final byDescription = <String, String>{};
  for (final flow in flows) {
    final file = File(context.absolute(flow));
    if (!file.existsSync()) continue;
    for (final description in testDescriptions(file.readAsStringSync())) {
      byDescription[description] = flow;
    }
  }
  final suspects = <String>{};
  for (final description in failing) {
    final flow = byDescription[description];
    if (flow == null) return const [];
    suspects.add(flow);
  }
  return suspects.toList()..sort();
}

/// The descriptions of the `testWidgets` / `test` calls in a flow's [source],
/// with adjacent string literals joined.
List<String> testDescriptions(String source) {
  final call = RegExp(r'''\b(?:testWidgets|test)\(\s*((?:(?:'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")\s*)+),''');
  final literal = RegExp(r''''((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"''');
  return [
    for (final match in call.allMatches(source))
      [
        for (final part in literal.allMatches(match.group(1) ?? ''))
          (part.group(1) ?? part.group(2) ?? '').replaceAllMapped(RegExp(r'\\(.)'), (m) => m.group(1) ?? ''),
      ].join(),
  ];
}

// ------------------------------------------------------------------ background

/// The folder of the background run's state, result and log.
const backgroundDir = 'build/neon-check/background';

/// A fingerprint of the working tree: HEAD, every uncommitted change and the
/// content of untracked files (the Claude Code Stop hook uses the same one).
String treeFingerprint(String root) {
  final result = Process.runSync(
    'bash',
    [
      '-c',
      '{ git rev-parse HEAD; git status --porcelain=v1 --untracked-files=all; git diff HEAD; '
          'git ls-files --others --exclude-standard -z | xargs -0 -r sha1sum; } 2>/dev/null | sha1sum | cut -c1-16',
    ],
    workingDirectory: root,
  );
  return (result.stdout as String).trim();
}

/// MemAvailable in MB, or `null` where `/proc/meminfo` does not exist.
int? availableMemoryMb() {
  final file = File('/proc/meminfo');
  if (!file.existsSync()) return null;
  final match = RegExp(r'^MemAvailable:\s+(\d+) kB', multiLine: true).firstMatch(file.readAsStringSync());
  final kb = int.tryParse(match?.group(1) ?? '');
  return kb == null ? null : kb ~/ 1024;
}

/// The background run of the app at a root: `state.json` written when it is
/// started, `result.json` written by the run itself when it ends.
final class BackgroundRun {
  BackgroundRun(this.root);

  final String root;

  File get _state => File('$root/$backgroundDir/state.json');
  File get _result => File('$root/$backgroundDir/result.json');
  String get logPath => '$backgroundDir/run.log';

  Map<String, Object?>? _read(File file) {
    if (!file.existsSync()) return null;
    try {
      return jsonDecode(file.readAsStringSync()) as Map<String, Object?>;
    } on FormatException {
      return null;
    }
  }

  bool get exists => _state.existsSync();

  String get fingerprint => '${_read(_state)?['fingerprint'] ?? ''}';

  String get startedAt => '${_read(_state)?['started'] ?? ''}';

  List<String> get flows => [for (final flow in (_read(_state)?['flows'] as List<Object?>?) ?? const []) '$flow'];

  int get _pid => (_read(_state)?['pid'] as int?) ?? 0;

  /// The result, `null` while the run has not written one.
  ({List<FlowFailure> failed})? get result {
    final data = _read(_result);
    if (data == null) return null;
    return (
      failed: [
        for (final entry in (data['failed'] as List<Object?>?) ?? const [])
          if (entry is Map<String, Object?>) (flow: '${entry['flow']}', log: '${entry['log'] ?? ''}'),
      ],
    );
  }

  /// Started, without a result yet, and its process is alive.
  bool get running =>
      exists && !_result.existsSync() && _pid > 0 && Process.runSync('kill', ['-0', '$_pid']).exitCode == 0;

  /// Starts `neon-check integration --record` for [flows] detached, at low
  /// priority, its output in [logPath].
  Future<void> start({required String toolRoot, required List<String> flows, required String fingerprint}) async {
    Directory('$root/$backgroundDir').createSync(recursive: true);
    if (_result.existsSync()) _result.deleteSync();
    final process = await Process.start(
      'bash',
      [
        '-c',
        r'exec nice -n 10 "$0" integration --record "$@" >"$NEON_BG_LOG" 2>&1',
        '$toolRoot/bin/neon-check',
        ...flows,
      ],
      workingDirectory: root,
      environment: {'NEON_BG_LOG': '$root/$logPath', 'NEON_BG_FINGERPRINT': fingerprint},
      mode: ProcessStartMode.detached,
    );
    _state.writeAsStringSync(
      jsonEncode({
        'pid': process.pid,
        'fingerprint': fingerprint,
        'flows': flows,
        'started': DateTime.now().toIso8601String(),
      }),
    );
  }

  /// Written by the run itself (`integration --record`).
  void writeResult(List<FlowFailure> failed) {
    Directory('$root/$backgroundDir').createSync(recursive: true);
    _result.writeAsStringSync(
      jsonEncode({
        'fingerprint': Platform.environment['NEON_BG_FINGERPRINT'] ?? '',
        'failed': [
          for (final failure in failed) {'flow': failure.flow, 'log': failure.log},
        ],
        'finished': DateTime.now().toIso8601String(),
      }),
    );
  }

  /// Stops a running run (its whole process group: neon-check, run.sh,
  /// chromedriver, flutter drive) and forgets it.
  void cancel({required String integrationDir}) {
    final pid = _pid;
    if (running) {
      final group = Process.runSync('ps', ['-o', 'pgid=', '-p', '$pid']);
      final pgid = (group.stdout as String).trim();
      Process.runSync('kill', ['-TERM', '--', pgid.isEmpty ? '$pid' : '-$pgid']);
      final target = File('$root/$integrationDir/$combinedTargetName');
      if (target.existsSync()) target.deleteSync();
    }
    clear();
  }

  void clear() {
    for (final file in [_state, _result]) {
      if (file.existsSync()) file.deleteSync();
    }
  }
}
