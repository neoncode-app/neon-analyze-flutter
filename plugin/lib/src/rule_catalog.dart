import 'dart:convert';

import 'package:analysis_server_plugin/registry.dart';
import 'package:analyzer/analysis_rule/analysis_rule.dart';

import 'package:neon_lints/main.dart';

/// One rule as the catalog describes it.
typedef RuleEntry = ({String name, String kind, String description, String message, String correction});

/// Every rule the plugin registers, in registration order.
List<RuleEntry> ruleCatalog() {
  final registry = _CollectingRegistry();
  plugin.register(registry);
  return registry.entries;
}

/// [ruleCatalog] as the JSON of `rule_catalog.json`.
String ruleCatalogJson() => '${const JsonEncoder.withIndent('  ').convert({
          '_comment': 'Generated by tool/generate_rule_catalog.dart from the rule classes; do not edit.',
          'rules': {
            for (final rule in ruleCatalog())
              rule.name: {
                'kind': rule.kind,
                'description': rule.description,
                'message': rule.message,
                'correction': rule.correction,
              },
          },
        })}\n';

class _CollectingRegistry implements PluginRegistry {
  final entries = <RuleEntry>[];

  void _add(AbstractAnalysisRule rule, String kind) {
    final code = rule.diagnosticCodes.first;
    entries.add((
      name: rule.name,
      kind: kind,
      description: rule.description,
      message: code.problemMessage.replaceFirst('[NEON] ', ''),
      correction: code.correctionMessage ?? '',
    ));
  }

  @override
  void registerLintRule(AbstractAnalysisRule rule) => _add(rule, 'lint');

  @override
  void registerWarningRule(AbstractAnalysisRule rule) => _add(rule, 'warning');

  @override
  dynamic noSuchMethod(Invocation invocation) => null;
}
